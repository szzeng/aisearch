"""Download, export, and manifest the P0-03 Chinese-CLIP ViT-B-16 artifacts."""

from __future__ import annotations

import argparse
import importlib.metadata
import platform
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import torch
from chinese_clip_common import (
    CONTEXT_LENGTH,
    EMBEDDING_DIMENSION,
    IMAGE_SIZE,
    MODEL_ID,
    MODEL_REVISION,
    artifact_record,
    default_model_dir,
    write_json,
)
from huggingface_hub import HfApi, snapshot_download
from transformers import ChineseCLIPModel, ChineseCLIPProcessor

SOURCE_BASE_URL = f"https://huggingface.co/{MODEL_ID}"
LICENSE_URL = "https://huggingface.co/OFA-Sys/chinese-clip-vit-base-patch16/blob/main/LICENSE"
REQUIRED_REPOSITORY_FILES = (
    "config.json",
    "model.safetensors",
    "preprocessor_config.json",
    "tokenizer_config.json",
    "special_tokens_map.json",
    "vocab.txt",
)


class ImageTower(torch.nn.Module):
    def __init__(self, model: ChineseCLIPModel) -> None:
        super().__init__()
        self.vision_model = model.vision_model
        self.visual_projection = model.visual_projection

    def forward(self, pixel_values: torch.Tensor) -> torch.Tensor:
        pooled = self.vision_model(pixel_values=pixel_values).pooler_output
        return self.visual_projection(pooled)


class TextTower(torch.nn.Module):
    def __init__(self, model: ChineseCLIPModel) -> None:
        super().__init__()
        self.text_model = model.text_model
        self.text_projection = model.text_projection

    def forward(
        self, input_ids: torch.Tensor, attention_mask: torch.Tensor, token_type_ids: torch.Tensor
    ) -> torch.Tensor:
        pooled = self.text_model(
            input_ids=input_ids, attention_mask=attention_mask, token_type_ids=token_type_ids
        ).pooler_output
        return self.text_projection(pooled)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model-dir", type=Path, default=default_model_dir())
    parser.add_argument(
        "--manifest",
        type=Path,
        default=Path("tools/prepare_models/manifests/chinese-clip-vit-b-16.json"),
    )
    parser.add_argument("--revision", default=MODEL_REVISION)
    return parser.parse_args()


def versions() -> dict[str, str]:
    packages = (
        "huggingface-hub",
        "onnx",
        "onnxruntime",
        "pillow",
        "torch",
        "torchvision",
        "transformers",
    )
    return {name: importlib.metadata.version(name) for name in packages}


def export_onnx(
    model: ChineseCLIPModel, processor: ChineseCLIPProcessor, model_dir: Path
) -> dict[str, Any]:
    image_tower, text_tower = ImageTower(model).eval(), TextTower(model).eval()
    image_path, text_path = model_dir / "image_tower.fp32.onnx", model_dir / "text_tower.fp32.onnx"
    pixel_values = torch.zeros((1, 3, IMAGE_SIZE, IMAGE_SIZE), dtype=torch.float32)
    tokens = processor.tokenizer(
        "一只猫",
        padding="max_length",
        truncation=True,
        max_length=CONTEXT_LENGTH,
        return_tensors="pt",
    )
    with torch.inference_mode():
        torch.onnx.export(
            image_tower,
            (pixel_values,),
            image_path,
            input_names=["pixel_values"],
            output_names=["unnorm_image_features"],
            opset_version=17,
            dynamo=False,
        )
        torch.onnx.export(
            text_tower,
            (tokens["input_ids"], tokens["attention_mask"], tokens["token_type_ids"]),
            text_path,
            input_names=["input_ids", "attention_mask", "token_type_ids"],
            output_names=["unnorm_text_features"],
            opset_version=17,
            dynamo=False,
        )
    return {
        "image": artifact_record(image_path, model_dir, "generated by this script"),
        "text": artifact_record(text_path, model_dir, "generated by this script"),
    }


def main() -> int:
    args = parse_args()
    model_dir, manifest_path = args.model_dir.resolve(), args.manifest.resolve()
    completed_steps: list[str] = []
    try:
        model_dir.mkdir(parents=True, exist_ok=True)
        resolved_revision = HfApi().model_info(MODEL_ID, revision=args.revision).sha
        snapshot_download(
            repo_id=MODEL_ID,
            revision=resolved_revision,
            local_dir=model_dir,
            allow_patterns=list(REQUIRED_REPOSITORY_FILES),
        )
        completed_steps.append("download")
        missing = [name for name in REQUIRED_REPOSITORY_FILES if not (model_dir / name).is_file()]
        if missing:
            raise FileNotFoundError(f"download did not provide required files: {missing}")
        model = ChineseCLIPModel.from_pretrained(model_dir, local_files_only=True).eval()
        processor = ChineseCLIPProcessor.from_pretrained(model_dir, local_files_only=True)
        if model.config.projection_dim != EMBEDDING_DIMENSION:
            raise ValueError(
                f"expected {EMBEDDING_DIMENSION}-D embeddings, got {model.config.projection_dim}"
            )
        onnx_artifacts = export_onnx(model, processor, model_dir)
        completed_steps.append("onnx_export")
        repository_files = {
            name: artifact_record(
                model_dir / name, model_dir, f"{SOURCE_BASE_URL}/resolve/{resolved_revision}/{name}"
            )
            for name in REQUIRED_REPOSITORY_FILES
        }
        manifest = {
            "schema_version": 1,
            "model": {
                "name": "Chinese-CLIP ViT-B-16",
                "id": MODEL_ID,
                "requested_revision": args.revision,
                "resolved_revision": resolved_revision,
                "source_url": SOURCE_BASE_URL,
            },
            "artifacts": {"repository_files": repository_files, "onnx": onnx_artifacts},
            "preprocessing": {
                "image_size": IMAGE_SIZE,
                "resize": {"shortest_edge": IMAGE_SIZE},
                "center_crop": {"height": IMAGE_SIZE, "width": IMAGE_SIZE},
                "interpolation": "bicubic",
                "mean": list(processor.image_processor.image_mean),
                "std": list(processor.image_processor.image_std),
                "channel_order": "RGB",
                "dtype": "float32",
            },
            "tokenizer": {
                "name": processor.tokenizer.__class__.__name__,
                "vocab_file": "vocab.txt",
                "vocab_sha256": repository_files["vocab.txt"]["sha256"],
                "max_length": CONTEXT_LENGTH,
                "truncation": "right",
                "padding": "max_length",
            },
            "embedding": {
                "normalization": "L2",
                "dimension": model.config.projection_dim,
                "metric": "cosine",
            },
            "onnx": {
                "opset": 17,
                "batch": 1,
                "image": {
                    "inputs": {"pixel_values": [1, 3, IMAGE_SIZE, IMAGE_SIZE]},
                    "output": "unnorm_image_features",
                },
                "text": {
                    "inputs": {
                        "input_ids": [1, CONTEXT_LENGTH],
                        "attention_mask": [1, CONTEXT_LENGTH],
                        "token_type_ids": [1, CONTEXT_LENGTH],
                    },
                    "output": "unnorm_text_features",
                },
            },
            "runtime": {
                "backend": "onnxruntime",
                "versions": versions(),
                "device": "CPU",
                "precision": "FP32",
                "python": platform.python_version(),
                "platform": platform.platform(),
            },
            "license": {"spdx": "Apache-2.0", "source_url": LICENSE_URL},
            "generated_at_utc": datetime.now(UTC).isoformat(),
            "generator": "tools/prepare_models/download_and_export_chinese_clip.py",
            "artifact_root_note": "All paths are relative to the user-selected model directory, not this repository.",
        }
        write_json(manifest_path, manifest)
        completed_steps.append("manifest")
        print(
            {
                "status": "pass",
                "model_dir": str(model_dir),
                "manifest": str(manifest_path),
                "completed_steps": completed_steps,
            }
        )
        return 0
    except Exception as error:
        print(
            {
                "status": "fail",
                "stage": completed_steps[-1] if completed_steps else "download_or_setup",
                "exception_type": type(error).__name__,
                "message": str(error),
                "completed_steps": completed_steps,
            },
            file=sys.stderr,
        )
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
