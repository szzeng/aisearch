"""P0-03's final Chinese-CLIP download, ONNX export, and manifest command."""

from __future__ import annotations

import argparse
import importlib.metadata
import platform
import sys
from datetime import UTC, datetime
from pathlib import Path

import torch
from chinese_clip_common import (
    CONTEXT_LENGTH,
    IMAGE_SIZE,
    MODEL_ID,
    artifact_record,
    default_model_dir,
    write_json,
)
from huggingface_hub import HfApi, snapshot_download
from transformers import ChineseCLIPModel, ChineseCLIPProcessor

FILES = (
    "clip_cn_vit-b-16.pt",
    "config.json",
    "preprocessor_config.json",
    "pytorch_model.bin",
    "vocab.txt",
)
BASE = f"https://huggingface.co/{MODEL_ID}"


class ImageTower(torch.nn.Module):
    def __init__(self, model: ChineseCLIPModel) -> None:
        super().__init__()
        self.model = model

    def forward(self, pixel_values: torch.Tensor) -> torch.Tensor:
        return self.model.get_image_features(pixel_values=pixel_values)


class TextTower(torch.nn.Module):
    def __init__(self, model: ChineseCLIPModel) -> None:
        super().__init__()
        self.model = model

    def forward(
        self, input_ids: torch.Tensor, attention_mask: torch.Tensor, token_type_ids: torch.Tensor
    ) -> torch.Tensor:
        return self.model.get_text_features(
            input_ids=input_ids, attention_mask=attention_mask, token_type_ids=token_type_ids
        )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model-dir", type=Path, default=default_model_dir())
    parser.add_argument(
        "--manifest",
        type=Path,
        default=Path("tools/prepare_models/manifests/chinese-clip-vit-b-16.json"),
    )
    args = parser.parse_args()
    directory, manifest_path = args.model_dir.resolve(), args.manifest.resolve()
    steps: list[str] = []
    try:
        directory.mkdir(parents=True, exist_ok=True)
        revision = HfApi().model_info(MODEL_ID, revision="main").sha
        snapshot_download(
            MODEL_ID, revision=revision, local_dir=directory, allow_patterns=list(FILES)
        )
        if missing := [name for name in FILES if not (directory / name).is_file()]:
            raise FileNotFoundError(f"required files missing: {missing}")
        steps.append("download")
        model = ChineseCLIPModel.from_pretrained(directory, local_files_only=True).eval()
        processor = ChineseCLIPProcessor.from_pretrained(directory, local_files_only=True)
        if model.config.projection_dim != 512:
            raise ValueError(f"expected 512 dimensions, got {model.config.projection_dim}")
        image_path, text_path = (
            directory / "image_tower.fp32.onnx",
            directory / "text_tower.fp32.onnx",
        )
        tokens = processor.tokenizer(
            "一只猫",
            padding="max_length",
            truncation=True,
            max_length=CONTEXT_LENGTH,
            return_tensors="pt",
        )
        with torch.inference_mode():
            torch.onnx.export(
                ImageTower(model),
                (torch.zeros(1, 3, IMAGE_SIZE, IMAGE_SIZE),),
                image_path,
                input_names=["pixel_values"],
                output_names=["unnorm_image_features"],
                opset_version=17,
                dynamo=False,
            )
            torch.onnx.export(
                TextTower(model),
                (tokens["input_ids"], tokens["attention_mask"], tokens["token_type_ids"]),
                text_path,
                input_names=["input_ids", "attention_mask", "token_type_ids"],
                output_names=["unnorm_text_features"],
                opset_version=17,
                dynamo=False,
            )
        steps.append("onnx_export")
        source = lambda name: f"{BASE}/resolve/{revision}/{name}"
        repo = {name: artifact_record(directory / name, directory, source(name)) for name in FILES}
        onnx = {
            "image": artifact_record(image_path, directory, "generated by this script"),
            "text": artifact_record(text_path, directory, "generated by this script"),
        }
        versions = {
            name: importlib.metadata.version(name)
            for name in (
                "huggingface-hub",
                "onnx",
                "onnxruntime",
                "pillow",
                "torch",
                "torchvision",
                "transformers",
            )
        }
        manifest = {
            "schema_version": 1,
            "model": {
                "name": "Chinese-CLIP ViT-B-16",
                "id": MODEL_ID,
                "requested_revision": "main",
                "resolved_revision": revision,
                "source_url": BASE,
            },
            "artifacts": {"repository_files": repo, "onnx": onnx},
            "preprocessing": {
                "image_size": IMAGE_SIZE,
                "resize": {"shortest_edge": IMAGE_SIZE},
                "center_crop": {"height": IMAGE_SIZE, "width": IMAGE_SIZE},
                "interpolation": "bicubic",
                "mean": list(processor.image_processor.image_mean),
                "std": list(processor.image_processor.image_std),
                "channel_order": "RGB",
                "dtype": "float32",
            },
            "tokenizer": {
                "name": processor.tokenizer.__class__.__name__,
                "vocab_file": "vocab.txt",
                "vocab_sha256": repo["vocab.txt"]["sha256"],
                "max_length": CONTEXT_LENGTH,
                "truncation": "right",
                "padding": "max_length",
            },
            "embedding": {"normalization": "L2", "dimension": 512, "metric": "cosine"},
            "onnx": {
                "opset": 17,
                "batch": 1,
                "image": {
                    "inputs": {"pixel_values": [1, 3, IMAGE_SIZE, IMAGE_SIZE]},
                    "output": "unnorm_image_features",
                },
                "text": {
                    "inputs": {
                        "input_ids": [1, CONTEXT_LENGTH],
                        "attention_mask": [1, CONTEXT_LENGTH],
                        "token_type_ids": [1, CONTEXT_LENGTH],
                    },
                    "output": "unnorm_text_features",
                },
            },
            "runtime": {
                "backend": "onnxruntime",
                "versions": versions,
                "device": "CPU",
                "precision": "FP32",
                "python": platform.python_version(),
                "platform": platform.platform(),
            },
            "license": {"spdx": "Apache-2.0", "source_url": f"{BASE}/blob/main/LICENSE"},
            "generated_at_utc": datetime.now(UTC).isoformat(),
            "generator": "tools/prepare_models/prepare_chinese_clip_v2.py",
            "artifact_root_note": "All artifact paths are relative to the user-selected model directory, outside the repository.",
        }
        write_json(manifest_path, manifest)
        print(
            {
                "status": "pass",
                "completed_steps": [*steps, "manifest"],
                "model_dir": str(directory),
                "manifest": str(manifest_path),
            }
        )
        return 0
    except Exception as error:
        print(
            {
                "status": "fail",
                "stage": steps[-1] if steps else "setup",
                "exception_type": type(error).__name__,
                "message": str(error),
                "completed_steps": steps,
            },
            file=sys.stderr,
        )
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
